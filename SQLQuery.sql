CREATE OR ALTER VIEW VW_DIM_PRODUCTS
AS
(
SELECT DENSE_RANK() OVER(ORDER BY CATEGORY, BRAND) AS PRODUCT_KEY, CATEGORY, BRAND
FROM SALES_DATASET
GROUP BY CATEGORY, BRAND
)

SELECT * FROM VW_DIM_PRODUCTS

CREATE OR ALTER VIEW VW_DIM_STORE
AS
(
SELECT DENSE_RANK() OVER(ORDER BY CITY, STORE_FORMAT) AS STORE_KEY, CITY, STORE_FORMAT
FROM SALES_DATASET
GROUP BY CITY, STORE_FORMAT
)

SELECT * FROM VW_DIM_STORE

CREATE OR ALTER VIEW VW_DIM_CUSTOMERS
AS
(
SELECT DENSE_RANK() OVER(ORDER BY CUSTOMER_GENDER, CUSTOMER_AGE, LOYALTY_FLAG) AS CUSTOMER_KEY,
ISNULL(CUSTOMER_GENDER, 'UNKNOWN') AS CUSTOMER_GENDER,
ISNULL(CUSTOMER_AGE, 1) AS CUSTOMER_AGE,
CASE 
WHEN CUSTOMER_AGE IS NULL THEN 'UNKNOWN'
WHEN CUSTOMER_AGE < 25 THEN 'UNDER 25'
WHEN CUSTOMER_AGE BETWEEN 25 AND 40 THEN '25-40'
WHEN CUSTOMER_AGE BETWEEN 41 AND 60 THEN '41-60'
ELSE '60+'
END AS AGE_GROUP,
CASE
WHEN LOYALTY_FLAG = 1 THEN 'LOYAL'
ELSE 'STANDARD'
END AS LOYALITY_STATUS
FROM SALES_DATASET
GROUP BY CUSTOMER_GENDER, CUSTOMER_AGE, LOYALTY_FLAG
)

SELECT * FROM VW_DIM_CUSTOMERS


CREATE OR ALTER VIEW VW_DIM_PAYMENT_MODE
AS
(
SELECT DENSE_RANK() OVER(ORDER BY PAYMENT_MODE, CHANNEL) AS PAYMENT_KEY,
PAYMENT_MODE, CHANNEL
FROM SALES_DATASET
GROUP BY PAYMENT_MODE, CHANNEL
)

SELECT * FROM VW_DIM_PAYMENT_MODE


CREATE OR ALTER VIEW VW_DIM_INVOICE
AS
(
SELECT DENSE_RANK() OVER(ORDER BY INVOICE_ID, INVOICE_DATE) AS INVOICE_KEY,
INVOICE_ID, INVOICE_DATE, YEAR(INVOICE_DATE) AS IV_YEAR, DATEPART(QQ, INVOICE_DATE) AS IV_QUARTER, MONTH(INVOICE_DATE) AS IV_MONTH, DAY(INVOICE_DATE) AS IV_DAY
FROM SALES_DATASET
GROUP BY INVOICE_ID, INVOICE_DATE
)

SELECT * FROM VW_DIM_INVOICE


CREATE OR ALTER VIEW VW_FACTS
AS
(
SELECT P.PRODUCT_KEY, ST.STORE_KEY, C.CUSTOMER_KEY, PY.PAYMENT_KEY, I.INVOICE_KEY, CONVERT(DATE, S.INVOICE_DATE) AS DATE_KEY, S.UNITS, S.COST_PRICE,
S.SELLING_PRICE, S.REVENUE, S.COST, S.MARGIN, S.MARGIN_PERCENTAGE, S.STOCK_ON_HAND
FROM SALES_DATASET AS S
LEFT JOIN 
VW_DIM_PRODUCTS AS P
ON S.CATEGORY = P.CATEGORY AND S.BRAND = P.BRAND
LEFT JOIN
VW_DIM_STORE AS ST
ON S.CITY = ST.CITY AND S.STORE_FORMAT = ST.STORE_FORMAT
LEFT JOIN
VW_DIM_CUSTOMERS AS C
ON ISNULL(S.CUSTOMER_AGE, 1) = C.CUSTOMER_AGE AND 
ISNULL(S.CUSTOMER_GENDER, 'UNKNOWN') = C.CUSTOMER_GENDER AND
(CASE WHEN S.LOYALTY_FLAG = 1 THEN 'LOYAL' ELSE 'STANDARD' END) = C.LOYALITY_STATUS
LEFT JOIN
VW_DIM_PAYMENT_MODE AS PY
ON S.PAYMENT_MODE = PY.PAYMENT_MODE AND S.CHANNEL = PY.CHANNEL
LEFT JOIN
VW_DIM_INVOICE AS I
ON S.INVOICE_ID = I.INVOICE_ID AND S.INVOICE_DATE = I.INVOICE_DATE
)

 SELECT * FROM VW_FACTS



